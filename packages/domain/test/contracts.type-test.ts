// Compile-time tests of the contracts (WP-07): `tsc --noEmit` (npm run typecheck, npm run types:check) fails if one
// breaks. Nothing here runs. expectTypeOf-style assertions written as types, so they need no library and no
// expect-error directive (the type ratchet counts those): a negative case is "not assignable", checked as a type.
//
// The unions that carry science words are pinned to the place they are copied from: a word added to, dropped from or
// misspelt in one of them fails here.

import type { Db } from '@atlas/data';
import type { MISSING_STATES, MissingState } from '@atlas/data/rows';
import type {
  Actor, AnyScenario, ChangeRecord, ChangeStatus, CommandResult, ConstraintId, EngineMissing, GateVerdict, GradeId, Group,
  MaterialId, MeasurementId, MissingWord, Proposal, ProposalState, ReasonCode, RowSubject, ScenarioConstraint, ScenarioDecision,
  ServiceMoisture, SourceId, StateId, Status, Verdict, WriteCommand,
} from '../src/contracts/index.ts';
import type { GATE_PRECEDENCE, GATE_STATUS, GATE_TABLE } from '../src/core/gate-verdict.ts';

// ------------------------------------------------------------------ the assertion kit

type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends (<T>() => T extends B ? 1 : 2) ? true : false;
type Assignable<From, To> = [From] extends [To] ? true : false;
type Expect<T extends true> = T;
type Not<T extends boolean> = T extends true ? false : true;
type Keys<T> = keyof T;

// The kit itself: equal is exact, not merely mutual assignability.
export type KitChecks = [
  Expect<Equal<'a', 'a'>>,
  Expect<Not<Equal<'a', 'a' | 'b'>>>,
  Expect<Not<Equal<{ a?: 1 }, { a: 1 | undefined }>>>,
  Expect<Not<Assignable<string, 'a'>>>,
];

// ------------------------------------------------------------------ science words

// A product's gate in the compiled database (schema/db.schema.json enum, generated by WP-06). A material's gates are
// still a bare object there (research gap-5 section 3 item 6), so the product's is the one the schema pins.
type DbGate = Extract<Db['grades'][number]['print'], { nozzle: unknown }>['nozzle']['verdict'];

export type GateVerdictChecks = [
  // The contract's six verdicts are the table's, in its precedence, and the compiled database's (schema enum).
  Expect<Equal<GateVerdict, (typeof GATE_PRECEDENCE)[number]>>,
  Expect<Equal<GateVerdict, Keys<typeof GATE_TABLE>>>,
  Expect<Equal<GateVerdict, Keys<typeof GATE_STATUS>>>,
  Expect<Equal<GateVerdict, DbGate>>,
  Expect<Equal<(typeof GATE_PRECEDENCE)['length'], 6>>,
  // A misspelling, a retired verdict (partial, D151) and a label are not verdicts.
  Expect<Not<Assignable<'Within', GateVerdict>>>,
  Expect<Not<Assignable<'partial', GateVerdict>>>,
  Expect<Not<Assignable<'on the line', GateVerdict>>>,
  // Each verdict answers with one of the engine's statuses; edge and exceeds-recommended never fail (D6, D151).
  Expect<Equal<(typeof GATE_STATUS)['exceeds'], 'FAIL'>>,
  Expect<Equal<(typeof GATE_STATUS)['exceeds-recommended'], 'INDETERMINATE'>>,
  Expect<Equal<(typeof GATE_STATUS)['edge'], 'INDETERMINATE'>>,
  Expect<Equal<(typeof GATE_STATUS)['within-low-end'], 'PASS'>>,
  Expect<Equal<(typeof GATE_STATUS)['unknown'], 'UNKNOWN'>>,
];

export type MissingWordChecks = [
  // The six words of schema/vocab/missing-states.csv, no more, no fewer.
  Expect<Equal<MissingWord, MissingState>>,
  Expect<Equal<(typeof MISSING_STATES)['length'], 6>>,
  Expect<Equal<MissingWord, 'Not published' | 'Not applicable' | 'Insufficient comparable data' | 'Unresolved unit / layout' | 'Not recorded' | 'Not available in sampled Canadian market'>>,
  // A missing word is never a number, never blank, and not the engine's own missing kind.
  Expect<Not<Assignable<0, MissingWord>>>,
  Expect<Not<Assignable<'', MissingWord>>>,
  Expect<Not<Assignable<'not-published', MissingWord>>>,
  Expect<Assignable<'not-published', EngineMissing>>,
  Expect<Not<Assignable<'not-publsihed', EngineMissing>>>,
  Expect<Not<Assignable<string, EngineMissing>>>,
];

export type StatusChecks = [
  Expect<Equal<Status, 'PASS' | 'FAIL' | 'UNKNOWN' | 'INDETERMINATE'>>,
  // A product's verdict is never indeterminate: evaluateMaterial gives PASS, FAIL or UNKNOWN.
  Expect<Equal<Verdict, 'PASS' | 'FAIL' | 'UNKNOWN'>>,
  Expect<Not<Assignable<'pass', Status>>>,
  Expect<Equal<Group, 'meets' | 'one-check-away' | 'not-enough-data' | 'unlikely-to-meet' | 'hidden' | 'fail'>>,
  // A service state is dry or conditioned; 'not-stated' is a measurement's, never a scenario's.
  Expect<Equal<ServiceMoisture, 'dry' | 'conditioned'>>,
  // The engine's own treatment requirement is not one a scenario may hold (scenario.js KINDS refuses it).
  Expect<Not<Assignable<{ kind: 'treatment' }, ScenarioConstraint>>>,
  Expect<Assignable<{ kind: 'gate'; gate: 'nozzle' }, ScenarioConstraint>>,
];

export type StateChecks = [
  Expect<Equal<ChangeStatus, 'draft' | 'exported' | 'merged'>>,
  Expect<Equal<ProposalState, 'pending' | 'accepted' | 'rejected' | 'held'>>,
  Expect<Assignable<'as-printed', StateId>>,
  Expect<Assignable<'annealed:120:16+conditioned', StateId>>,
  Expect<Assignable<'annealed:x:16', StateId>>,
  Expect<Not<Assignable<'dry', StateId>>>,
  Expect<Not<Assignable<'conditioned+annealed:120:16', StateId>>>,
];

export type ReasonCodeChecks = [
  // The two reasons the engine parses back with a regex today (constraints.js:948-949) have codes.
  Expect<Assignable<'gate.no-print-profile', ReasonCode>>,
  Expect<Assignable<'gate.no-temperature-published', ReasonCode>>,
  Expect<Not<Assignable<'No print profile recorded', ReasonCode>>>,
  Expect<Not<Assignable<string, ReasonCode>>>,
];

// ------------------------------------------------------------------ distinct IDs

export type IdChecks = [
  Expect<Not<Assignable<GradeId, MaterialId>>>,
  Expect<Not<Assignable<MaterialId, GradeId>>>,
  Expect<Not<Assignable<MeasurementId, MaterialId>>>,
  Expect<Not<Assignable<SourceId, ConstraintId>>>,
  Expect<Not<Assignable<ConstraintId, SourceId>>>,
  // A plain or unchecked string is not an ID until a guard says so (core/ids.ts).
  Expect<Not<Assignable<string, SourceId>>>,
  Expect<Not<Assignable<'M001', MaterialId>>>,
  // An ID is still a string where a string is wanted.
  Expect<Assignable<MaterialId, string>>,
];

// ------------------------------------------------------------------ states that cannot be built

type HeldWithoutReason = { state: 'held' };
type AgentWithoutModel = { kind: 'agent'; name: string };
type CorrectionWithoutEvidence = Omit<Extract<WriteCommand, { kind: 'correctValue' }>, 'evidence'>;
type StaleWithoutValues = { status: 'refused'; code: 'stale'; detail: string };
type StaleWithEmptyValues = { status: 'refused'; code: 'stale'; detail: string; expected: {}; current: {} };
type RecordedCorrectionWithoutEvidence = Omit<Extract<ChangeRecord, { kind: 'correctValue' }>, 'evidence'>;
type ProductRowWithoutState = { materialId: MaterialId; productId: GradeId };
type TargetBoth = { productId: GradeId; unresolvedIdentity: string };

export type IllegalStateChecks = [
  Expect<Not<Assignable<HeldWithoutReason, Proposal['status']>>>,
  Expect<Not<Assignable<AgentWithoutModel, Actor>>>,
  Expect<Not<Assignable<CorrectionWithoutEvidence, WriteCommand>>>,
  Expect<Not<Assignable<StaleWithoutValues, CommandResult>>>,
  Expect<Not<Assignable<StaleWithEmptyValues, CommandResult>>>,
  Expect<Not<Assignable<RecordedCorrectionWithoutEvidence, ChangeRecord>>>,
  Expect<Not<Assignable<ProductRowWithoutState, RowSubject>>>,
  Expect<Assignable<{ materialId: MaterialId }, RowSubject>>,
  Expect<Not<Assignable<TargetBoth, Proposal['target']>>>,
  // Each write kind narrows to its own command, so a handler per kind keeps its type.
  Expect<Not<Equal<Extract<WriteCommand, { kind: 'retireRecord' }>, never>>>,
  // A saved decision as decisionOf writes it, with no note, is a decision.
  Expect<Assignable<{ gradeId: 'G001-01'; stateId: null; release: null; chosenOn: null; note: null; tests: [] }, ScenarioDecision>>,
  // A scenario of an unknown version is neither v1 nor v2.
  Expect<Not<Assignable<{ version: 3 }, AnyScenario>>>,
];
