#!/usr/bin/env node
// The rule against the hand: for every headline value selected in headlines.csv, the value the product rule
// (build/src/products.js) chooses on the same grade with no selection to follow, and where the hand-picked product sits
// among its material's products. Re-center phase 1's gate: the rule should agree with at least nine picks in ten, and
// every disagreement is listed for the owner, because phase 4 retires the hand picks the rule reproduces. Since m137
// retired them, the picks and each material's representative grade are read from their archive,
// docs/audits/2026-09-25-re-center/retired-representative-picks.csv, so the comparison can still be re-run.
//
//   node scripts/audit/rule-vs-hand-picks.mjs   writes docs/audits/2026-09-25-re-center/rule-vs-hand-picks.md

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTables, snapshotDate } from '../../build/src/load.js';
import { readCsv } from '../../build/src/csv.js';
import { buildDatabase } from '../../build/src/pipeline.js';
import { measurementHeadlines } from '../../build/src/registry.js';
import { ruleValue } from '../../build/src/products.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const out = join(root, 'docs/audits/2026-09-25-re-center/rule-vs-hand-picks.md');

const wb = loadTables(join(root, 'data'));
const archive = readCsv(join(root, 'docs/audits/2026-09-25-re-center/retired-representative-picks.csv')).records.map((r) => r.values);
const representativeOf = new Map(archive.map((r) => [r.MaterialID, r['Representative grade']]));
const { db } = buildDatabase(wb, { snapshot: snapshotDate(wb.Method.rows), build: 'audit', estimates: false });
const defs = new Map(measurementHeadlines(db.registry).map((d) => [d.key, d]));
const measurementById = new Map(db.measurements.map((m) => [m.id, m]));
const gradeById = new Map(db.grades.map((g) => [g.id, g]));
const materialById = new Map(db.materials.map((m) => [m.id, m]));
const byGrade = new Map();
for (const m of db.measurements) {
  if (!byGrade.has(m.gradeId)) byGrade.set(m.gradeId, []);
  byGrade.get(m.gradeId).push(m);
}

const fmt = (v) => (v == null ? '—' : Number(v.toPrecision(6)).toString());
const rows = [];
const picked = new Set();
for (const s of archive.filter((r) => r.Use === 'value')) {
  const def = defs.get(s.HeadlineKey);
  const m = measurementById.get(s.MeasurementID);
  if (!def || !m) continue;
  picked.add(`${s.MaterialID}|${s.HeadlineKey}`);
  const grade = gradeById.get(m.gradeId);
  const rule = ruleValue(grade, def, byGrade.get(grade.id) ?? []);
  const outcome = !rule ? 'rule has none' : rule.measurementId === m.id ? 'same measurement' : rule.value === m.value ? 'same value' : 'different';
  // Where the hand-picked product sits among its material's comparable products: the share at or below its value.
  const summary = materialById.get(s.MaterialID)?.summary?.[s.HeadlineKey];
  const values = (materialById.get(s.MaterialID)?.gradeIds ?? []).map((id) => gradeById.get(id))
    .filter((g) => g && !g.variant && g.headline?.[s.HeadlineKey]?.level === 'comparable').map((g) => g.headline[s.HeadlineKey].value);
  const rank = values.length > 1 ? `${Math.round((values.filter((v) => v <= m.value).length / values.length) * 100)} %` : '';
  rows.push({ material: materialById.get(s.MaterialID)?.name ?? s.MaterialID, id: s.MaterialID, key: s.HeadlineKey, grade: grade.id,
    pick: m.id, pickValue: m.value, rule: rule?.measurementId ?? '', ruleValue: rule?.value, ruleLevel: rule?.level ?? '', outcome,
    n: summary?.n ?? 0, median: summary?.median, rank });
}

// Headlines nobody picked where the representative grade publishes a value the rule accepts.
const added = [];
for (const mat of db.materials.filter((x) => !x.familyEntry && gradeById.has(representativeOf.get(x.id)))) {
  const g = gradeById.get(representativeOf.get(mat.id));
  for (const [key, def] of defs) {
    if (picked.has(`${mat.id}|${key}`) || mat.headline[key]?.notApplicable) continue;
    const rule = ruleValue(g, def, byGrade.get(g.id) ?? []);
    if (rule) added.push({ material: mat.name, id: mat.id, key, grade: g.id, rule: rule.measurementId, value: rule.value, level: rule.level, caveat: rule.caveat ?? '' });
  }
}

const count = (o) => rows.filter((r) => r.outcome === o).length;
const agree = count('same measurement') + count('same value');
const pct = (n) => `${((n / rows.length) * 100).toFixed(1)} %`;
const lines = [
  '# The product rule against the hand picks',
  '',
  'Generated by `node scripts/audit/rule-vs-hand-picks.mjs`; nothing here is written by hand. For every value row of',
  '`data/tables/headlines.csv`, the value the product rule (`build/src/products.js`) chooses on the same grade when no',
  'selection tells it what to take, and where the hand-picked product sits among its material\'s products. Re-center',
  'phase 1\'s gate asks for nine in ten to agree and every disagreement listed.',
  '',
  '| Outcome | Selections | Share |',
  '|---|---:|---:|',
  ...['same measurement', 'same value', 'different', 'rule has none'].map((o) => `| ${o} | ${count(o)} | ${pct(count(o))} |`),
  `| **agree (same measurement or value)** | **${agree}** | **${pct(agree)}** |`,
  '',
  '## Where they disagree',
  '',
  'The hand pick stays the product\'s value until phase 4: `headlines.csv` pins it. Each row wants a decision: keep the pin',
  '(and give it a reason in phase 4), or let the rule choose.',
  '',
  '| Material | Headline | Grade | Hand pick | Rule | Rule\'s level |',
  '|---|---|---|---|---|---|',
  ...rows.filter((r) => r.outcome === 'different' || r.outcome === 'rule has none')
    .map((r) => `| ${r.material} (${r.id}) | ${r.key} | ${r.grade} | ${r.pick}: ${fmt(r.pickValue)} | ${r.rule ? `${r.rule}: ${fmt(r.ruleValue)}` : '—'} | ${r.ruleLevel} |`),
  '',
  '## Headlines the rule fills that nobody picked',
  '',
  `On the representative grade, ${added.length} headline(s) the hand left empty have a value the rule accepts. The material`,
  'headline does not change in phase 1; the product value is there for the engine in phase 2.',
  '',
  '| Material | Headline | Grade | Rule | Level |',
  '|---|---|---|---|---|',
  ...added.map((a) => `| ${a.material} (${a.id}) | ${a.key} | ${a.grade} | ${a.rule}: ${fmt(a.value)} | ${a.level}${a.caveat ? ` (${a.caveat})` : ''} |`),
  '',
  '## Where the hand-picked product sits in its material',
  '',
  'The share of the material\'s comparable products at or below the picked value, for materials with more than one.',
  'A pick near 0 % or 100 % made the material look weaker or stronger than its typical product.',
  '',
  '| Material | Headline | Picked | Comparable products | Median | Share at or below |',
  '|---|---|---:|---:|---:|---:|',
  ...rows.filter((r) => r.rank).sort((a, b) => a.material.localeCompare(b.material) || a.key.localeCompare(b.key))
    .map((r) => `| ${r.material} | ${r.key} | ${fmt(r.pickValue)} | ${r.n} | ${fmt(r.median)} | ${r.rank} |`),
  '',
];
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`${rows.length} selections: ${agree} agree (${pct(agree)}), ${count('different')} different, ${count('rule has none')} with no rule value; ${added.length} filled by the rule -> ${out}`);
