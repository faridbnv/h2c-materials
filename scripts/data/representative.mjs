#!/usr/bin/env node
// Which grade stands for each material (PLAN-REMAINING 2.4). A material's headlines and its estimate are read at
// its Representative grade (compile.js, estimate/observations.js), and those were chosen when most materials had one
// grade. The import brought 1,119; this reports, per material, how much of the headline set the current grade
// publishes and which active procurement grade publishes the most, so the owner can confirm the moves in one pass.
//
//   npm run data:representative            write docs/audits/2026-09-18-v2-import/representative-grades.md
//   npm run data:representative -- --check exit 1 if that file is out of date
//
// A grade "covers" a headline where it publishes a value the build could select for it: the headline's property,
// unit and direction (and 0.45 MPa for heat deflection), a published number not flagged implausible, a printed or
// unstated specimen, not moisture-conditioned. Price is left out: it is a median over listings, not a grade's row.
// The report decides nothing; the move is a migration that changes Representative grade and headlines.csv together.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { openTables, projectRoot } from './table-io.mjs';
import { specimenForm } from '../../build/src/normalize/specimen.js';

const OUT = join(projectRoot, 'docs/audits/2026-09-18-v2-import/representative-grades.md');
const t = openTables();
const defs = t.rows('headline_definitions').filter((d) => d.Kind === 'measurement');
const list = (v) => (v && !/^Not /.test(v) ? v.split(/\s*;\s*/) : []);
const HEADLINES = defs.map((d) => ({ key: d.HeadlineKey, properties: list(d['Value properties']), unit: d.Unit,
  direction: /^Not /.test(d.Direction) ? null : d.Direction, load: /^Not /.test(d['Load MPa']) ? null : d['Load MPa'] }));

const covers = (m, h) => h.properties.includes(m.Property) && m['Normalized unit'] === h.unit
  && (!h.direction || m.Direction === h.direction)
  && (!h.load || m['Test load MPa'] === h.load)
  && /^Published value( \(transcription corrected\))?$/.test(m['Data status'])
  && m.Operator !== '<' && m.Operator !== '<='
  && ['printed', 'not-stated'].includes(specimenForm(m['Specimen type']))
  && m['Moisture state'] !== 'conditioned';

const byGrade = new Map();
for (const m of t.rows('measurements')) {
  if (!byGrade.has(m.GradeID)) byGrade.set(m.GradeID, []);
  byGrade.get(m.GradeID).push(m);
}
const profile = (gradeId) => {
  const rows = byGrade.get(gradeId) ?? [];
  const keys = HEADLINES.filter((h) => rows.some((m) => covers(m, h))).map((h) => h.key);
  // How many of those headlines a printed bar covers, not merely an unstated one.
  const printed = HEADLINES.filter((h) => rows.some((m) => covers(m, h) && specimenForm(m['Specimen type']) === 'printed')).length;
  return { keys, printed, rows: rows.length };
};
const short = { density: 'ρ', tensileModulusXY: 'E', tensileStrengthXY: 'σ', elongationXY: 'ε', hdt045: 'HDT' };
const keysText = (p) => (p.keys.length ? p.keys.map((k) => short[k] ?? k).join(' ') : '—');
const gradeText = (g, p) => `${g.GradeID} ${g.Manufacturer} ${g['Product name']} (${keysText(p)})`;

const moves = [];
const none = [];
const held = [];
for (const mat of t.rows('materials')) {
  if (mat.Scope === 'Family entry') continue;
  const grades = t.rows('grades').filter((g) => g.MaterialID === mat.MaterialID && g.Status === 'active');
  const repId = mat['Representative grade'];
  const rep = /^G/.test(repId ?? '') ? t.find('grades', repId) : null;
  const candidates = grades.filter((g) => g.Role === 'procurement')
    .map((g) => ({ g, p: profile(g.GradeID) }))
    .sort((a, b) => b.p.keys.length - a.p.keys.length || b.p.printed - a.p.printed || b.p.rows - a.p.rows || a.g.GradeID.localeCompare(b.g.GradeID));
  const best = candidates[0];
  if (!rep) {
    none.push({ mat, best, n: grades.length });
    continue;
  }
  const cur = profile(rep.GradeID);
  const retired = rep.Status !== 'active';
  if (best && best.g.GradeID !== rep.GradeID && (retired || best.p.keys.length > cur.keys.length)) {
    moves.push({ mat, rep, cur, best, n: grades.length, retired });
  } else if (best && best.g.GradeID !== rep.GradeID && best.p.keys.length === cur.keys.length && best.p.printed > cur.printed) {
    held.push({ mat, rep, cur, best, n: grades.length });
  }
}

const md = [
  '# Representative grades after the import (PLAN-REMAINING 2.4)',
  '',
  'Generated by `npm run data:representative`; do not edit. A material\'s headlines and its estimate are read at its',
  'Representative grade. The letters are the headlines a grade publishes a selectable value for: ρ density, E tensile',
  'modulus XY, σ tensile strength XY, ε elongation at break XY, HDT heat deflection at 0.45 MPa (printed or unstated',
  'specimen, not conditioned, not flagged implausible). The report decides nothing: a move is one migration that',
  'changes `Representative grade` and the `headlines.csv` rows together, and names the coverage rows that go stale.',
  '',
  `## Materials whose best-documented grade publishes more (${moves.length})`,
  '',
  'Tick the ones to move. Where the current grade is the maker the material was named after, keeping it may be the',
  'better choice even with fewer headlines; that is the judgement this list is for.',
  '',
  '| Move? | Material | Grades | Current | Best documented |',
  '|---|---|---:|---|---|',
  ...moves.map(({ mat, rep, cur, best, n, retired }) => `| [ ] | ${mat.MaterialID} ${mat['Original name']} | ${n} | ${gradeText(rep, cur)}${retired ? ' **retired**' : ''} | ${gradeText(best.g, best.p)} |`),
  '',
  `## As many headlines, more of them printed (${held.length})`,
  '',
  'The current grade publishes as many headlines as the best one, but fewer of them from bars its sheet calls printed.',
  'The recommendation is to keep the current grade unless the owner prefers the printed evidence.',
  '',
  '| Material | Current | Printed alternative |',
  '|---|---|---|',
  ...held.map(({ mat, rep, cur, best }) => `| ${mat.MaterialID} ${mat['Original name']} | ${gradeText(rep, cur)}, ${cur.printed} of ${cur.keys.length} printed | ${gradeText(best.g, best.p)}, ${best.p.printed} of ${best.p.keys.length} printed |`),
  '',
  `## Materials with no representative grade (${none.length})`,
  '',
  '| Material | Active grades | Best documented |',
  '|---|---:|---|',
  ...none.map(({ mat, best, n }) => `| ${mat.MaterialID} ${mat['Original name']} | ${n} | ${best ? gradeText(best.g, best.p) : '—'} |`),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== md) { console.error(`${OUT} is out of date: npm run data:representative`); process.exit(1); }
  console.log('representative-grades.md is current');
} else {
  writeFileSync(OUT, md);
  console.log(`representative-grades.md: ${moves.length} to decide, ${held.length} printed alternatives, ${none.length} with none`);
}
