// are already applied.
//
// **How each row was matched.** Every source whose document is cached and hash-checked was read again with the
// current reader, and a proposed row was matched to a recorded one only where the property and the value as
// printed agree — and, where two rows of a property share a value, the direction as well. A row is corrected
// only where the record says "Not published" and the re-read names a standard; nothing else is touched, and no
// value moves. 1,512 rows name no standard, 457 sources were re-read, and 481 rows gain what their sheet prints.
//
// Four eSUN rows gain a method that names the load as well as the standard, and their typed Test load MPa
// column says 0.45 with it: a typed column that says a load is not published beside a raw text that states it
// is exactly what PARSE-MISMATCH is for.
//
