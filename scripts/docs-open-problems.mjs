#!/usr/bin/env node
// The counts at the head of docs/OPEN-PROBLEMS.md, each re-derived rather than remembered (maintainability round,
// 2026-10-15). The page's items say what is wrong or missing in words and give the query behind each figure; this table
// is the figures that change most, written from the build so a stale number cannot sit at the top of the page.
//
// The queries are docs/open-problems-queries.json: SQL against dist/h2c.sqlite's raw and compiled tables (never the
// record tier, which only a checkout with the private cache holds), or a count of the committed build snapshot's rows.
// Writing the SQLite file takes some twenty seconds, so this runs at a round's close (npm run round:close), not in verify.
//
//   npm run docs:open-problems              rewrite the table (the SQLite file first, if it is not of the tables)
//   npm run docs:open-problems -- --check   exit 1 if the table is not what the build gives now

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCsv } from '../build/src/csv.js';
import { ensureCurrent, queryFile } from './data/sqlite.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(root, 'docs/OPEN-PROBLEMS.md');
const START = '<!-- counts:begin -->';
const END = '<!-- counts:end -->';

/** Each count's value, in the order the queries list them. */
export function counts(queries, { out = join(root, 'dist/h2c.sqlite') } = {}) {
  let stamp = null;
  const snapshots = new Map();
  return queries.map((q) => {
    if (q.sql) {
      stamp ??= ensureCurrent(root, out).stamp;
      const [row] = queryFile(out, q.sql).rows;
      return { ...q, value: Number(Object.values(row)[0]) };
    }
    if (!snapshots.has(q.snapshot)) snapshots.set(q.snapshot, readCsv(join(root, q.snapshot)).records.map((r) => r.values));
    return { ...q, value: snapshots.get(q.snapshot).filter((r) => r[q.column] === q.equals).length };
  }).map((c) => ({ ...c, release: stamp?.['release.id'] ?? null }));
}

export function table(rows) {
  const release = rows.find((r) => r.release)?.release;
  return [
    START,
    `<!-- Generated by npm run docs:open-problems from release ${release} (dist/h2c.sqlite and build/snapshot); edit docs/open-problems-queries.json, not this table. -->`,
    '| What | Count | Item |',
    '|---|---:|---|',
    ...rows.map((r) => `| ${r.label} | ${r.value.toLocaleString('en-US')} | ${/^\d/.test(r.item) ? `§${r.item}` : r.item} |`),
    END,
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { counts: queries } = JSON.parse(readFileSync(join(root, 'docs/open-problems-queries.json'), 'utf8'));
  const page = readFileSync(PAGE, 'utf8');
  if (!page.includes(START) || !page.includes(END)) { console.error('docs/OPEN-PROBLEMS.md has no counts block'); process.exit(1); }
  const next = page.slice(0, page.indexOf(START)) + table(counts(queries)) + page.slice(page.indexOf(END) + END.length);
  if (process.argv.includes('--check')) {
    if (next !== page) { console.error('docs/OPEN-PROBLEMS.md counts are out of date; run npm run docs:open-problems'); process.exit(1); }
    console.log('docs/OPEN-PROBLEMS.md counts are current');
  } else {
    writeFileSync(PAGE, next);
    console.log('docs/OPEN-PROBLEMS.md: counts rewritten');
  }
}
