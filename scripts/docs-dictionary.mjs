#!/usr/bin/env node
// Generate docs/DATA-DICTIONARY.md from schema/: every table, every column (role, type, what it may hold, where it
// points), and every vocabulary with its meanings.
//   npm run docs:dictionary            rewrite the file
//   npm run docs:dictionary -- --check exit 1 if it is out of date (run by npm run verify)
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCsv } from '../build/src/csv.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const path = join(root, 'docs/DATA-DICTIONARY.md');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const ROLE = {
  key: 'identifier', canonical: 'decides behaviour', raw: 'as the source prints it', editorial: 'a curation choice', prose: 'explanation for readers',
};

const tables = readdirSync(join(root, 'schema/tables')).filter((f) => f.endsWith('.schema.json')).sort()
  .map((f) => ({ name: basename(f, '.schema.json'), schema: JSON.parse(readFileSync(join(root, 'schema/tables', f), 'utf8')) }));
const vocabs = readdirSync(join(root, 'schema/vocab')).filter((f) => f.endsWith('.csv')).sort()
  .map((f) => ({ name: basename(f, '.csv'), ...readCsv(join(root, 'schema/vocab', f)) }));

const L = ['# Data dictionary', '', '<!-- Generated by npm run docs:dictionary from schema/. Do not edit by hand. -->', '',
  'Every table under `data/tables/` and every vocabulary under `schema/vocab/`, as the schema gate enforces them.',
  'Roles: a **key** identifies the row; a **canonical** column decides behaviour and is checked; a **raw** column keeps',
  'the source\'s own text; an **editorial** column records a curation choice; a **prose** column explains. "May be"',
  'lists the missing states a column accepts instead of a value; a blank required cell is always an error.', '',
  // Schema only: row counts would make the page stale on every data edit.
  '## Tables', '', '| Table | Key | Holds |', '|---|---|---|',
  ...tables.map(({ name, schema }) => `| [${name}](#${name}) | ${schema.primaryKey ?? (schema.uniqueKeys?.[0] ?? []).join(' + ')} | ${esc(schema.description)} |`), ''];

for (const { name, schema } of tables) {
  L.push(`### ${name}`, '', `\`data/tables/${name}.csv\` (${esc(schema.title ?? name)}). ${esc(schema.description)}`, '',
    '| Column | Role | Type | Required | May be | Points to / values | Description |', '|---|---|---|---|---|---|---|');
  for (const f of schema.fields) {
    const target = f.reference ? `→ ${f.reference.table}.${f.reference.field}`
      : f.item?.reference ? `list of → ${f.item.reference.table}.${f.item.reference.field}`
      : f.vocabulary ? `[${f.vocabulary}](#vocab-${f.vocabulary})`
      : f.item?.vocabulary ? `list of [${f.item.vocabulary}](#vocab-${f.item.vocabulary})`
      : f.constraints?.enum ? f.constraints.enum.join(', ')
      : f.constraints?.pattern ? `\`${f.constraints.pattern}\`` : '';
    L.push(`| ${esc(f.name)} | ${f.role ?? ''} | ${f.type}${f.delimiter ? ` ("${f.delimiter}")` : ''} | ${f.constraints?.required ? 'yes' : ''} | ${esc((f.missing ?? []).join(', '))} | ${esc(target)} | ${esc(f.description)} |`);
  }
  L.push('');
}

L.push('## Vocabularies', '');
for (const v of vocabs) {
  const usedBy = tables.flatMap(({ name, schema }) => schema.fields.filter((f) => f.vocabulary === v.name || f.item?.vocabulary === v.name).map((f) => `${name}.${f.name}`));
  const extra = v.header.filter((h) => h !== 'Value' && h !== 'Meaning');
  L.push(`<a id="vocab-${v.name}"></a>`, `### ${v.name}`, '', `\`schema/vocab/${v.name}.csv\`${usedBy.length ? `, used by ${usedBy.join(', ')}` : ''}.`, '',
    `| Value | Meaning |${extra.map((h) => ` ${h} |`).join('')}`, `|---|---|${extra.map(() => '---|').join('')}`,
    ...v.records.map((r) => `| ${esc(r.values.Value)} | ${esc(r.values.Meaning)} |${extra.map((h) => ` ${esc(r.values[h])} |`).join('')}`), '');
}
L.push(`Role meanings: ${Object.entries(ROLE).map(([k, v]) => `${k}, ${v}`).join('; ')}.`, '');

const text = L.join('\n');
if (process.argv.includes('--check')) {
  if (!existsSync(path) || readFileSync(path, 'utf8') !== text) { console.error('docs/DATA-DICTIONARY.md is out of date; run npm run docs:dictionary'); process.exit(1); }
  console.log('docs/DATA-DICTIONARY.md is current');
} else {
  writeFileSync(path, text);
  console.log(`docs/DATA-DICTIONARY.md: ${tables.length} tables, ${vocabs.length} vocabularies`);
}
