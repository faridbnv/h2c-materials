#!/usr/bin/env node
// Back-check of the guide's drying against products that state their own (D127, gap round 2).
//
// The build now reads a printer maker's guide row for the drying of a product whose own sheets, and its twin's, say nothing
// on it (build/src/products.js, amending D88). That is sound only if the guide agrees with the products that do state theirs.
// For every active product that states its own drying temperature and whose material has a read guide row
// (print_guide_materials.csv), this compares the guide's temperature window with the product's, and the guide's need with
// the product's. It writes guide-drying-backcheck.md beside it, with counts and every disagreement.
//
//   node docs/audits/2026-10-05-gap-round-2/guide-drying-backcheck.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { openTables } from '../../../scripts/data/table-io.mjs';
import { parseDrying } from '../../../build/src/normalize/process.js';

const here = dirname(fileURLToPath(import.meta.url));
const t = openTables();

// The first temperature a drying cell prints, as a window [lo, hi] (a point has lo = hi). A guide cell names two methods
// (a blast drying oven, then the X1 heatbed); the first, the oven, is the drying temperature the guide gives.
function windowOf(text) {
  const first = String(text).split(/X1 Series/i)[0].replace(/[–—]/g, '-');
  const range = first.match(/(\d{2,3})\s*(?:°|˚|º)?\s*C?\s*(?:-|~|to)\s*(\d{2,3})\s*(?:°|˚|º)?\s*[C℃]/i);
  if (range) return [Number(range[1]), Number(range[2])];
  const point = first.match(/(\d{2,3})\s*(?:°|˚|º)?\s*[C℃]/i);
  const typed = parseDrying(text).tempC;
  if (point) return [Number(point[1]), Number(point[1])];
  return typed != null ? [typed, typed] : null;
}

const guides = new Map(t.rows('print_guide').map((g) => [g.PrintGuideID, g]));
const guideOf = new Map();
for (const m of t.rows('print_guide_materials')) guideOf.set(m.MaterialID, guides.get(m.PrintGuideID));
const products = t.rows('grades').filter((g) => g.Status === 'active' && g.Role === 'procurement');
const profiles = t.rows('profiles').filter((p) => p.Profile !== 'Retired duplicate record');

const rows = [];
for (const g of products) {
  const guide = guideOf.get(g.MaterialID);
  if (!guide || guide.Drying === 'Not published') continue;
  const own = profiles.filter((p) => p.GradeID === g.GradeID && p['Drying state'] === 'stated' && p['Drying °C'] !== 'Not published' && p['Drying °C'] !== 'Not applicable');
  if (!own.length) continue;
  const gw = windowOf(guide.Drying);
  const ownNeed = ['required', 'optional', 'not-needed'].find((n) => own.some((p) => p['Drying need'] === n));
  for (const p of own) {
    // The product's window from its own words where they print one ("50-60℃"); else the typed temperature.
    const pw = windowOf(p.Drying) ?? [Number(p['Drying °C']), Number(p['Drying °C'])];
    if (!gw) continue;
    const inside = pw[0] >= gw[0] && pw[1] <= gw[1];
    const overlaps = pw[0] <= gw[1] && pw[1] >= gw[0];
    rows.push({ grade: g.GradeID, product: `${g.Manufacturer} ${g['Product name']}`, material: g.MaterialID, guide: guide.PrintGuideID, type: guide['Guide type'],
      gw, pw, relation: inside ? 'contains' : overlaps ? 'overlaps' : 'disjoint', gap: inside || overlaps ? 0 : Math.min(Math.abs(pw[0] - gw[1]), Math.abs(gw[0] - pw[1])),
      guideNeed: guide['Drying need'], ownNeed: p['Drying need'], profile: p.ProfileID, ownText: p.Drying, ownNeedAll: ownNeed });
  }
}

const by = (list, key) => list.reduce((m, r) => m.set(key(r), (m.get(key(r)) ?? 0) + 1), new Map());
const productsChecked = new Set(rows.map((r) => r.grade));
const relation = by(rows, (r) => r.relation);
const needs = by(rows, (r) => `${r.guideNeed} / ${r.ownNeed}`);
const disagree = rows.filter((r) => r.relation === 'disjoint');
const needDisagree = rows.filter((r) => r.guideNeed !== r.ownNeed);
const span = (w) => (w[0] === w[1] ? `${w[0]}` : `${w[0]}-${w[1]}`);

const L = [];
L.push('# Guide drying against products that state their own (D127)', '');
L.push('Generated by `guide-drying-backcheck.mjs`. A guide row fills the drying of a product only where its own sheets and its twin\'s are silent;');
L.push('this checks the guide against the products that are not silent, on the same material. The guide\'s window is its first method (the blast');
L.push('drying oven); a product\'s is the window its own words print, else its typed temperature.', '');
L.push(`- Products checked: ${productsChecked.size} (profiles compared: ${rows.length}), over ${new Set(rows.map((r) => r.guide)).size} guide rows.`);
L.push(`- Temperature: the guide's window contains the product's ${relation.get('contains') ?? 0}, overlaps it ${relation.get('overlaps') ?? 0}, misses it ${relation.get('disjoint') ?? 0}.`);
L.push(`- Need, guide / product: ${[...needs].sort().map(([k, n]) => `${k} ${n}`).join('; ')}.`, '');
L.push('## Temperature disagreements (guide window misses the product\'s)', '');
if (!disagree.length) L.push('None.');
else {
  L.push('| Product | Guide row | Guide °C | Product °C | Gap °C | Profile |', '|---|---|---|---|---|---|');
  for (const r of disagree.sort((a, b) => b.gap - a.gap || a.grade.localeCompare(b.grade))) L.push(`| ${r.product} (${r.grade}) | ${r.guide} ${r.type} | ${span(r.gw)} | ${span(r.pw)} | ${r.gap} | ${r.profile} |`);
}
L.push('', '## Need disagreements (guide need differs from the product\'s)', '');
if (!needDisagree.length) L.push('None.');
else {
  L.push('| Product | Guide row | Guide need | Product need | Product\'s words |', '|---|---|---|---|---|');
  for (const r of needDisagree.sort((a, b) => a.grade.localeCompare(b.grade))) L.push(`| ${r.product} (${r.grade}) | ${r.guide} ${r.type} | ${r.guideNeed} | ${r.ownNeed} | ${r.ownText.replace(/\|/g, '/').slice(0, 70)} |`);
}
L.push('');
writeFileSync(join(here, 'guide-drying-backcheck.md'), L.join('\n'));
console.log(`products ${productsChecked.size}, profiles ${rows.length}: temperature contains ${relation.get('contains') ?? 0}, overlaps ${relation.get('overlaps') ?? 0}, disjoint ${relation.get('disjoint') ?? 0}; need disagreements ${needDisagree.length} (${[...needs].sort().map(([k, n]) => `${k} ${n}`).join('; ')})`);
